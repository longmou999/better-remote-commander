/**
 * Register the agent to start at login, per platform, without admin rights.
 *
 * Windows deliberately uses one long-lived hidden supervisor task. It does not
 * use periodic watchdog triggers or .cmd launchers, so normal health checks
 * cannot flash console windows every minute.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync, unlinkSync, existsSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const NAME = 'brc-agent';
const cliPath = () => fileURLToPath(new URL('./cli.js', import.meta.url));
const home = () => process.env.BRC_HOME ?? path.join(os.homedir(), '.brc');
const run = (cmd: string, args: string[]) => execFileSync(cmd, args, { stdio: 'pipe' }).toString();

export function installService(extraArgs: string[]): string {
  mkdirSync(home(), { recursive: true });
  const node = process.execPath;
  const args = [cliPath(), '--no-browser', ...extraArgs];
  const logFile = path.resolve(home(), 'agent.log');

  if (process.platform === 'win32') {
    const psQuote = (value: string) => `'${value.replace(/'/g, "''")}'`;
    const xml = (value: string) => value
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
    const dir = path.resolve(home());
    const powershell = path.join(
      process.env.SystemRoot ?? 'C:\\Windows',
      'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe',
    );

    // Detached legacy launchers cannot be safely replaced while their child is
    // still alive. Refuse migration instead of killing unrelated node.exe.
    const legacyFiles = ['start-agent.cmd', 'start-agent.vbs']
      .map((file) => path.join(dir, file))
      .filter(existsSync);
    if (legacyFiles.length) {
      run(powershell, [
        '-NoProfile', '-NonInteractive', '-Command',
        `$ErrorActionPreference='Stop'; $cli=${psQuote(cliPath())}; $agents=@(Get-CimInstance Win32_Process -Filter "Name='node.exe'" | Where-Object { $_.ProcessId -ne ${process.pid} -and $_.CommandLine -and $_.CommandLine.IndexOf($cli,[StringComparison]::OrdinalIgnoreCase) -ge 0 }); if($agents.Count){ throw 'legacy BRC Agent is still running; stop that specific process before migration' }`,
      ]);
    }

    const supervisor = path.join(dir, 'supervise-agent.ps1');
    const taskFile = path.join(dir, 'agent-task.xml');
    const mutex = 'Local\\BRCAgent-' + createHash('sha256')
      .update(dir.toLowerCase()).digest('hex').slice(0, 24);

    writeFileSync(supervisor, `\uFEFF# Generated by brc-agent --install-service
$ErrorActionPreference = 'Continue'
$env:BRC_HOME = ${psQuote(dir)}
Set-Location -LiteralPath $env:BRC_HOME
$log = ${psQuote(logFile)}
$mutex = New-Object System.Threading.Mutex($false, ${psQuote(mutex)})
$locked = $false
try {
  try { $locked = $mutex.WaitOne(0) }
  catch [System.Threading.AbandonedMutexException] { $locked = $true }
  if (-not $locked) { exit 0 }

  while ($true) {
    if ((Test-Path -LiteralPath $log) -and (Get-Item -LiteralPath $log).Length -gt 10MB) {
      Move-Item -LiteralPath $log -Destination ($log + '.1') -Force
    }
    try {
      & ${[node, ...args].map(psQuote).join(' ')} 2>&1 |
        Out-File -LiteralPath $log -Append -Encoding utf8
      ('{0:o} Agent exited ({1}); restart in 5s' -f (Get-Date), $LASTEXITCODE) |
        Out-File -LiteralPath $log -Append -Encoding utf8
    } catch {
      ('{0:o} Agent launch failed: {1}' -f (Get-Date), $_) |
        Out-File -LiteralPath $log -Append -Encoding utf8
    }
    Start-Sleep -Seconds 5
  }
} finally {
  if ($locked) { $mutex.ReleaseMutex() }
  $mutex.Dispose()
}
`, 'utf8');

    const user = process.env.USERNAME
      ? [process.env.USERDOMAIN, process.env.USERNAME].filter(Boolean).join('\\')
      : os.userInfo().username;

    writeFileSync(taskFile, `\uFEFF<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <Triggers>
    <LogonTrigger><Enabled>true</Enabled><UserId>${xml(user)}</UserId></LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>${xml(user)}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <StartWhenAvailable>true</StartWhenAvailable>
    <Hidden>true</Hidden>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <RestartOnFailure><Interval>PT1M</Interval><Count>999</Count></RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>${xml(powershell)}</Command>
      <Arguments>${xml(`-NoProfile -NonInteractive -WindowStyle Hidden -ExecutionPolicy Bypass -File "${supervisor}"`)}</Arguments>
      <WorkingDirectory>${xml(dir)}</WorkingDirectory>
    </Exec>
  </Actions>
</Task>
`, 'utf16le');

    run('schtasks', ['/Create', '/F', '/TN', NAME, '/XML', taskFile]);
    for (const file of legacyFiles) unlinkSync(file);
    run('schtasks', ['/Run', '/TN', NAME]);
    return `Installed Task Scheduler task "${NAME}" (one hidden logon supervisor; no periodic watchdog). Log: ${logFile}\nManage: schtasks /Query /TN ${NAME} | schtasks /End /TN ${NAME}`;
  }

  if (process.platform === 'linux') {
    const dir = path.join(os.homedir(), '.config', 'systemd', 'user');
    mkdirSync(dir, { recursive: true });
    const unit = path.join(dir, `${NAME}.service`);
    writeFileSync(unit, `[Unit]\nDescription=Better Remote Commander (BRC) device agent\nAfter=network-online.target\n\n[Service]\nExecStart=${node} ${args.join(' ')}\nRestart=always\nRestartSec=5\nEnvironment=BRC_HOME=${home()}\n\n[Install]\nWantedBy=default.target\n`);
    run('systemctl', ['--user', 'daemon-reload']);
    run('systemctl', ['--user', 'enable', '--now', `${NAME}.service`]);
    return `Installed systemd user unit ${unit}.\nTo keep it running when logged out: sudo loginctl enable-linger ${os.userInfo().username}\nLogs: journalctl --user -u ${NAME} -f`;
  }

  if (process.platform === 'darwin') {
    const dir = path.join(os.homedir(), 'Library', 'LaunchAgents');
    mkdirSync(dir, { recursive: true });
    const plist = path.join(dir, `dev.brc.${NAME}.plist`);
    const xmlArgs = [node, ...args].map((a) => `    <string>${a}</string>`).join('\n');
    writeFileSync(plist, `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0"><dict>\n  <key>Label</key><string>dev.brc.${NAME}</string>\n  <key>ProgramArguments</key><array>\n${xmlArgs}\n  </array>\n  <key>RunAtLoad</key><true/>\n  <key>KeepAlive</key><true/>\n  <key>StandardOutPath</key><string>${logFile}</string>\n  <key>StandardErrorPath</key><string>${logFile}</string>\n  <key>EnvironmentVariables</key><dict><key>BRC_HOME</key><string>${home()}</string></dict>\n</dict></plist>\n`);
    try { run('launchctl', ['unload', plist]); } catch { /* not loaded */ }
    run('launchctl', ['load', '-w', plist]);
    return `Installed LaunchAgent ${plist}. Log: ${logFile}`;
  }

  throw new Error(`unsupported platform ${process.platform}`);
}

export function uninstallService(): string {
  if (process.platform === 'win32') {
    try { run('schtasks', ['/End', '/TN', NAME]); } catch { /* not running */ }
    run('schtasks', ['/Delete', '/F', '/TN', NAME]);
    for (const file of ['start-agent.vbs', 'start-agent.cmd', 'supervise-agent.ps1', 'agent-task.xml']) {
      const p = path.join(home(), file);
      if (existsSync(p)) unlinkSync(p);
    }
    return `Removed Task Scheduler task "${NAME}". Stop any remaining exact brc-agent process separately; never kill all node.exe processes.`;
  }

  if (process.platform === 'linux') {
    const unit = path.join(os.homedir(), '.config', 'systemd', 'user', `${NAME}.service`);
    try { run('systemctl', ['--user', 'disable', '--now', `${NAME}.service`]); } catch { /* not enabled */ }
    if (existsSync(unit)) unlinkSync(unit);
    run('systemctl', ['--user', 'daemon-reload']);
    return `Removed systemd user unit ${NAME}.service.`;
  }

  if (process.platform === 'darwin') {
    const plist = path.join(os.homedir(), 'Library', 'LaunchAgents', `dev.brc.${NAME}.plist`);
    try { run('launchctl', ['unload', plist]); } catch { /* not loaded */ }
    if (existsSync(plist)) unlinkSync(plist);
    return `Removed LaunchAgent ${plist}.`;
  }

  throw new Error(`unsupported platform ${process.platform}`);
}
